# === TEMPERATURA === #
'creo la varibile "temperatura" e le do un valore numerico'
temperatura = 30

# SE la variabile "temperatura" supera 30
if temperatura > 30:
    # stampiamo "fa caldo"
    print("fa caldo")

# ALTRIMENTI SE la variabile "temperatura" è IDENTICA al numero 10
elif temperatura >= 10:
    # stampiamo "fa fresco"
    print("fa fresco")

# ALTRIMENTI 
else:
    # stampiamo "fa freddo"
    print("fa freddo")


